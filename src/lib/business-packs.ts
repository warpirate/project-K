import type { Flow, Rule } from "@/lib/rules";

export interface PackItem {
  name: string;
  flow: Flow;
  /** Usual price in paise; null when the amount differs every time. */
  price: number | null;
  fee?: Rule;
  portalCost?: Rule;
  aliases: string[];
}

export interface PackQuestion {
  ask: string;
  /** Default answer: true when most shops of this type do it. */
  on: boolean;
  items: PackItem[];
}

export interface BusinessPack {
  id: string;
  name: string;
  sub: string;
  /** Hint in the entry screen's search box. */
  search: string;
  /** Always added, e.g. "Other items" for a bill total. */
  base: PackItem[];
  questions: PackQuestion[];
}

