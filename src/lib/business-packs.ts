export const packById = (id: string | null | undefined) => BUSINESS_PACKS.find((p) => p.id === id);

/** Service types a business uses; "other" (or none picked) gets all of them. */
export function packFlows(pack: BusinessPack | undefined): Flow[] {
  const all: Flow[] = ["cash_out", "cash_in", "pay_through", "application", "counter_sale"];
  if (!pack || pack.questions.length === 0) return all;
  const used = new Set<Flow>(["counter_sale", ...pack.base.map((i) => i.flow), ...pack.questions.flatMap((q) => q.items.map((i) => i.flow))]);
  return all.filter((f) => used.has(f));
}

